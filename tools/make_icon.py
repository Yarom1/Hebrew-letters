"""Generates the launcher icon: three toy alphabet blocks (א ב ג) on a purple background.

The letters are taken from the bundled Rubik Bold font, so they match the app. Writes:

    app/src/main/res/drawable/ic_launcher_foreground.xml   (adaptive icon, Android 8+)
    app/src/main/res/drawable/ic_launcher_monochrome.xml   (themed icon, Android 13+)
    app/src/main/res/mipmap-anydpi/ic_launcher.xml         (round icon, Android 6-7)

Usage (from the repository root):

    pip install fonttools
    python3 tools/make_icon.py [preview.svg]

All coordinates are in the 108x108 adaptive-icon canvas. Everything important stays inside the
66-unit "safe zone" circle in the middle, so no launcher mask cuts it off.
"""
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT = "app/src/main/assets/fonts/Rubik-Bold.ttf"
RES = "app/src/main/res/"

BG_TOP, BG_BOTTOM = "#845EF7", "#5F3DC4"
STAR = "#FFD43B"
WHITE = "#FFFFFF"

# letter, centre x, centre y, rotation (degrees), face colour, darker edge colour
BLOCK = 22.0
BLOCKS = [
    ("ב", 42.5, 64.5, 5, "#37B24D", "#2B8A3E"),   # ב bottom left
    ("א", 65.5, 64.5, -6, "#F03E3E", "#C92A2A"),  # א bottom right (Hebrew reads right to left)
    ("ג", 54.0, 41.5, -3, "#FAB005", "#E67700"),  # ג on top
]
STARS = [(31.0, 37.0, 4.6), (77.5, 36.0, 3.6)]


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def glyph_path(font, char, cx, cy, height):
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[ord(char)]
    bounds = BoundsPen(glyphs)
    glyphs[name].draw(bounds)
    xmin, ymin, xmax, ymax = bounds.bounds
    s = height / (ymax - ymin)
    mx, my = (xmin + xmax) / 2, (ymin + ymax) / 2
    pen = SVGPathPen(glyphs, ntos=num)
    glyphs[name].draw(TransformPen(pen, (s, 0, 0, -s, cx - mx * s, cy + my * s)))
    return pen.getCommands()


def rounded_rect(x, y, w, h, r):
    return (f"M{num(x + r)},{num(y)}h{num(w - 2 * r)}a{num(r)},{num(r)} 0 0 1 {num(r)},{num(r)}"
            f"v{num(h - 2 * r)}a{num(r)},{num(r)} 0 0 1 {num(-r)},{num(r)}h{num(-(w - 2 * r))}"
            f"a{num(r)},{num(r)} 0 0 1 {num(-r)},{num(-r)}v{num(-(h - 2 * r))}"
            f"a{num(r)},{num(r)} 0 0 1 {num(r)},{num(-r)}z")


def star(cx, cy, r_outer, r_inner):
    import math
    pts = []
    for i in range(10):
        r = r_outer if i % 2 == 0 else r_inner
        a = -math.pi / 2 + i * math.pi / 5
        pts.append(f"{num(cx + r * math.cos(a))},{num(cy + r * math.sin(a))}")
    return "M" + " L".join(pts) + " Z"


def shapes(font):
    """Returns a list of (rotation, cx, cy, [(pathData, colour), ...]) groups."""
    groups = [(0, 54, 54, [(star(x, y, r, r * 0.45), STAR) for x, y, r in STARS])]
    for letter, cx, cy, rot, face, edge in BLOCKS:
        half = BLOCK / 2
        parts = [
            (rounded_rect(cx - half, cy - half + 2.6, BLOCK, BLOCK, 4.5), edge),   # thickness
            (rounded_rect(cx - half, cy - half, BLOCK, BLOCK, 4.5), face),         # front face
            (rounded_rect(cx - half + 2.2, cy - half + 2.2, BLOCK - 4.4, BLOCK - 4.4, 3), "#33FFFFFF"),
            (glyph_path(font, letter, cx, cy, 12.5), WHITE),
        ]
        groups.append((rot, cx, cy, parts))
    return groups


def vector_xml(groups, width_dp, background=None, comment=""):
    out = ['<?xml version="1.0" encoding="utf-8"?>']
    if comment:
        out.append(f"<!-- {comment} Generated by tools/make_icon.py -->")
    out.append('<vector xmlns:android="http://schemas.android.com/apk/res/android"')
    out.append(f'    android:width="{width_dp}dp"\n    android:height="{width_dp}dp"')
    out.append('    android:viewportWidth="108"\n    android:viewportHeight="108">')
    if background:
        out.append(f'    <path\n        android:fillColor="{background}"\n'
                   '        android:pathData="M54,4a50,50 0,1 1,0 100a50,50 0,1 1,0 -100z" />')
    for rot, cx, cy, parts in groups:
        indent = "    "
        if rot:
            out.append(f'    <group\n        android:pivotX="{num(cx)}"\n        android:pivotY="{num(cy)}"\n'
                       f'        android:rotation="{num(rot)}">')
            indent = "        "
        for data, colour in parts:
            out.append(f'{indent}<path\n{indent}    android:fillColor="{colour}"\n'
                       f'{indent}    android:pathData="{data}" />')
        if rot:
            out.append("    </group>")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def svg_colour(c):
    # #AARRGGBB -> rgba
    if len(c) == 9:
        a = int(c[1:3], 16) / 255
        return f'fill="#{c[3:]}" fill-opacity="{a:.2f}"'
    return f'fill="{c}"'


def preview_svg(groups, size=432):
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">',
           f'<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{BG_TOP}"/>'
           f'<stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>'
           '<clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath></defs>',
           '<g clip-path="url(#c)"><rect width="108" height="108" fill="url(#g)"/>']
    for rot, cx, cy, parts in groups:
        out.append(f'<g transform="rotate({rot} {cx} {cy})">')
        for data, colour in parts:
            out.append(f'<path d="{data}" {svg_colour(colour)}/>')
        out.append("</g>")
    out.append("</g></svg>")
    return "\n".join(out)


def main():
    font = TTFont(FONT)
    groups = shapes(font)
    with open(RES + "drawable/ic_launcher_foreground.xml", "w", encoding="utf-8") as f:
        f.write(vector_xml(groups, 108, comment="Toy blocks with the letters א ב ג."))
    with open(RES + "mipmap-anydpi/ic_launcher.xml", "w", encoding="utf-8") as f:
        f.write(vector_xml(groups, 48, background=BG_BOTTOM,
                           comment="Round icon for Android 6-7 (no adaptive icons there)."))
    mono = [(rot, cx, cy, [(glyph_path(font, letter, cx, cy, 15), "#FF000000")])
            for (letter, cx, cy, rot, _f, _e) in BLOCKS for rot in [rot]]
    with open(RES + "drawable/ic_launcher_monochrome.xml", "w", encoding="utf-8") as f:
        f.write(vector_xml(mono, 108, comment="Themed (single-colour) icon: the three letters."))
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w", encoding="utf-8") as f:
            f.write(preview_svg(groups))


if __name__ == "__main__":
    main()
